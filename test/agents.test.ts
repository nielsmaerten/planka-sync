import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { AGENTS_BLOCK, mergeAgentsMd, writeScaffold } from "../src/agents.ts";
import { validateRoot } from "../src/validate.ts";

/** An older block, as a previous planka-sync version would have written it. */
const OLD_BLOCK =
  "<!-- planka-sync:begin v3; generated -->\n# Old manual\n<!-- planka-sync:end -->\n";

function withRoot(fn: (root: string, agents: string) => void): void {
  const root = mkdtempSync(join(tmpdir(), "planka-sync-agents-"));
  try {
    fn(root, join(root, "AGENTS.md"));
  } finally {
    rmSync(root, { recursive: true });
  }
}

test("a missing or empty AGENTS.md gets just the block", () => {
  assert.equal(mergeAgentsMd(null), AGENTS_BLOCK);
  assert.equal(mergeAgentsMd("\n"), AGENTS_BLOCK);
});

test("the block is current, so a second run writes nothing", () => {
  withRoot((root, agents) => {
    assert.deepEqual(writeScaffold(root), ["AGENTS.md", ".gitignore"]);
    assert.equal(readFileSync(agents, "utf8"), AGENTS_BLOCK);
    assert.deepEqual(writeScaffold(root), []);
  });
});

test("a user's own AGENTS.md is kept and the block appended", () => {
  withRoot((root, agents) => {
    writeFileSync(agents, "# My project\n\nUse British spelling.");
    assert.ok(writeScaffold(root).includes("AGENTS.md (updated)"));
    assert.equal(
      readFileSync(agents, "utf8"),
      `# My project\n\nUse British spelling.\n\n${AGENTS_BLOCK}`,
    );
    assert.ok(!writeScaffold(root).some((w) => w.startsWith("AGENTS.md")));
  });
});

test("an outdated or edited block is replaced; text around it stays byte for byte", () => {
  const before = "# Mine\n\nNotes before.\n\n";
  const after = "\n## Also mine\nNotes after.\n";
  assert.equal(mergeAgentsMd(before + OLD_BLOCK + after), before + AGENTS_BLOCK + after);
  const edited = AGENTS_BLOCK.replace("Planka is", "Planka was");
  assert.equal(mergeAgentsMd(before + edited), before + AGENTS_BLOCK);
  assert.equal(mergeAgentsMd(before + AGENTS_BLOCK + after), before + AGENTS_BLOCK + after);
});

test("a v1-v3 AGENTS.md, generated whole, is replaced by the block", () => {
  const legacy =
    "<!-- planka-sync agents v3; generated by planka-sync, edits are overwritten -->\n# Old\n";
  assert.equal(mergeAgentsMd(legacy), AGENTS_BLOCK);
});

test("broken markers leave the file alone and validate warns", () => {
  const broken = [
    "mine\n<!-- planka-sync:begin v3 -->\nno end\n",
    "<!-- planka-sync:end -->\nmine\n<!-- planka-sync:begin v3 -->\n",
    OLD_BLOCK + OLD_BLOCK,
  ];
  for (const text of broken) assert.equal(mergeAgentsMd(text), null, text);
  withRoot((root, agents) => {
    writeFileSync(join(root, "planka-sync.yaml"), "server: s\nproject: '7'\n");
    writeFileSync(agents, broken[0]);
    writeScaffold(root);
    assert.equal(readFileSync(agents, "utf8"), broken[0]);
    assert.ok(validateRoot(root).warnings.some((w) => w.startsWith("AGENTS.md: ")));
  });
});
